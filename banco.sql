-- 1. Tipo enumerado para tipos de usuário
CREATE TYPE tipo_usuario AS ENUM ('fotografo', 'comum');

-- 2. Tabela de Usuários
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    senha TEXT NOT NULL,
    foto_perfil TEXT DEFAULT 'default.png',
    tipo tipo_usuario NOT NULL DEFAULT 'comum'
);

-- 3. Tabela de Publicações
CREATE TABLE publicacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE CASCADE NOT NULL,
    titulo TEXT NOT NULL,
    localizacao TEXT NOT NULL,
    imagem_url TEXT NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Tabela de Curtidas (Restrição: 1 curtida por usuário em cada foto)
CREATE TABLE curtidas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE CASCADE NOT NULL,
    publicacao_id BIGINT REFERENCES publicacoes(id) ON DELETE CASCADE NOT NULL,
    CONSTRAINT curtida_unica UNIQUE (usuario_id, publicacao_id)
);

-- Habilitar Políticas de Segurança (Row Level Security)
ALTER TABLE usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE publicacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE curtidas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Acesso público usuarios" ON usuarios FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso público publicacoes" ON publicacoes FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Acesso público curtidas" ON curtidas FOR ALL USING (true) WITH CHECK (true);
